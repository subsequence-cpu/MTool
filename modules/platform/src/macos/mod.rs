use mtool_core::Result;
use objc2::rc::autoreleasepool;
use objc2_app_kit::{NSPasteboard, NSWorkspace};
use objc2_foundation::NSString;
use std::{thread, time::Duration};

pub struct ClipboardWatcher;
impl ClipboardWatcher {
    pub fn new() -> Result<Self> {
        Ok(Self)
    }
    pub fn wait(&self) {
        thread::sleep(Duration::from_millis(300));
    }
}

pub fn clipboard_revision() -> u64 {
    autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount() as u64)
}

pub fn is_sensitive() -> bool {
    autoreleasepool(|_| {
        let Some(types) = NSPasteboard::generalPasteboard().types() else {
            return false;
        };
        types.iter().any(|kind| {
            matches!(
                kind.to_string().as_str(),
                "org.nspasteboard.ConcealedType"
                    | "org.nspasteboard.TransientType"
                    | "org.nspasteboard.AutoGeneratedType"
                    | "com.agilebits.onepassword"
                    | "dev.mtool.owned"
            )
        })
    })
}

pub fn mark_owned() {
    autoreleasepool(|_| {
        NSPasteboard::generalPasteboard().setString_forType(
            &NSString::from_str("1"),
            &NSString::from_str("dev.mtool.owned"),
        );
    });
}

pub fn clipboard_source() -> Option<String> {
    autoreleasepool(|_| {
        NSWorkspace::sharedWorkspace()
            .frontmostApplication()
            .and_then(|app| app.bundleIdentifier().or_else(|| app.localizedName()))
            .map(|name| name.to_string())
    })
}
